import { createHash } from "node:crypto"
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises"
import { fileURLToPath } from "node:url"
import path from "node:path"
import sharp from "sharp"
import nextEnvironment from "@next/env"

const root = fileURLToPath(new URL("../", import.meta.url))
nextEnvironment.loadEnvConfig(root, process.argv.includes("--development"))
const output = path.join(root, "public/pwa")
await mkdir(output, { recursive: true })

// Derive install icons mechanically from the existing INHALEX brand asset.
const logo = await sharp(path.join(root, "public/images/LogoSimple.png")).trim().toBuffer()
for (const [name, size, ratio] of [
  ["icon-192.png", 192, .78], ["icon-512.png", 512, .78],
  ["icon-maskable-512.png", 512, .58], ["apple-touch-icon.png", 180, .78],
]) {
  const mark = await sharp(logo).resize(Math.round(size * ratio), Math.round(size * ratio), { fit: "inside" }).toBuffer()
  await sharp({ create: { width: size, height: size, channels: 4, background: "#f7faf7" } })
    .composite([{ input: mark, gravity: "centre" }]).png().toFile(path.join(output, name))
}

const hash = createHash("sha256")
let originalImageBytes = 0, optimizedImageBytes = 0
for (const relative of ["Líneas/insomnio", "Líneas/ansiedad-estres", "Líneas/resfriado", "Líneas/verde", "Líneas/estimulante", "images/modo-de-uso"]) {
  const original = await readFile(path.join(root, "public", `${relative}.png`))
  const optimized = await sharp(original).resize({ width: 1400, withoutEnlargement: true }).webp({ quality: 82 }).toBuffer()
  await writeFile(path.join(root, "public", `${relative}.webp`), optimized)
  hash.update(relative).update(optimized)
  originalImageBytes += original.length; optimizedImageBytes += optimized.length
}
async function hashSources(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true })
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const relative = path.join(directory, entry.name)
    if (entry.isDirectory()) await hashSources(relative)
    else if (/\.(tsx?|m?js|css|html)$/.test(entry.name)) hash.update(relative).update(await readFile(path.join(root, relative)))
  }
}
for (const directory of ["app", "components", "lib", "pwa", "scripts"]) await hashSources(directory)
const apiUrl = (process.env.NEXT_PUBLIC_API_URL?.trim() || "http://localhost:3200/api").replace(/\/+$/, "")
const parsedApi = new URL(apiUrl)
if (!["http:", "https:"].includes(parsedApi.protocol) || parsedApi.username || parsedApi.password || parsedApi.search || parsedApi.hash) {
  throw new Error("NEXT_PUBLIC_API_URL must be a public HTTP(S) base URL without credentials, query or fragment")
}
hash.update(apiUrl).update(logo)
const version = hash.digest("hex").slice(0, 16)
const precache = ["/offline.html", "/pwa/offline.css", "/pwa/offline.js", "/pwa-config.json",
  "/pwa/icon-192.png", "/pwa/icon-512.png", "/pwa/icon-maskable-512.png", "/pwa/apple-touch-icon.png"]
for (const [source, target] of [["offline.html", "offline.html"], ["offline.css", "pwa/offline.css"], ["offline.js", "pwa/offline.js"]]) {
  await writeFile(path.join(root, "public", target), await readFile(path.join(root, "pwa", source)))
}
const worker = await readFile(path.join(root, "pwa/service-worker.js"), "utf8")
await writeFile(path.join(root, "public/sw.js"),
  `/* Generated by scripts/build-pwa.mjs. Edit pwa/service-worker.js. */\nconst BUILD_VERSION = ${JSON.stringify(version)};\nconst API_BASE_URL = ${JSON.stringify(apiUrl)};\nconst PRECACHE_URLS = ${JSON.stringify(precache)};\n${worker}`)
console.log(`INHALEX PWA ${version}: ${precache.length} lightweight shell resources; no videos or private pages.`)
console.log(`Six public illustrations: ${(originalImageBytes / 1048576).toFixed(2)} MiB PNG → ${(optimizedImageBytes / 1048576).toFixed(2)} MiB WebP. Originals preserved.`)
